-- CREAR UNA TABLA DE NOMBRE DETALLE_NOTAS, CON SUS PREFIJOS 
-- CORRESPONDIENTES, Y LOS SIGUIENTES CAMPOS: NRO_DETALLE, NOTA1, 
-- NOTA2, NOTA3, PROMEDIO, CON TODOS SUS CAMPOS DE TIPO NUMBER
-- Y RESTRICCIÓN PRIMARIA EN EL NRO_DETALLE.

CREATE TABLE CACB_DETALLE_NOTAS(
	NRO_DETALLE NUMBER,
	NOTA1 NUMBER,
	NOTA2 NUMBER,
	NOTA3 NUMBER,
	PROMEDIO NUMBER,
	CONSTRAINT PK_CACB_DETALLE_NOTAS PRIMARY KEY(NRO_DETALLE)
);


-- REALIZAR UN INSERT A ESTA TABLA

INSERT INTO CACB_DETALLE_NOTAS(NRO_DETALLE,NOTA1,NOTA2,NOTA3,PROMEDIO)
	VALUES(1,5,6,3,2.5);


-- CREAR UN TRIGGER QUE FUNCIONE CUANDO SE REALICE UN INSERT EN LA 
-- TABLA RECIÉN CREADA, QUE SE ENCARGUE DE GENERAR DE FORMA AUTOMÁTICA 
-- EL PROMEDIO LINEAL DE LAS NOTAS. ESTO, PARA QUE NO SEA NECESARIO 
-- AGREGAR EL VALOR DEL PROMEDIO EN EL INSERT ASOCIADO. Y ESTE SE 
-- CALCULE SOLO. DE NOMBRE PROMEDIO_AUTO


CREATE OR REPLACE TRIGGER CACB_PROMEDIO_AUTO
BEFORE INSERT
ON CACB_DETALLE_NOTAS
FOR EACH ROW
BEGIN
	:NEW.PROMEDIO := ROUND((:NEW.NOTA1+:NEW.NOTA2+:NEW.NOTA3)/3,1);
END;


-- CUANDO EL CAMPO NI VALOR SE DECLARAN, ESTE
-- SE ASUME NULO. Y PARA EVITAR ESTA SITUACIÓN LLEVANDO EL CONTROL
-- DE LA SIUTACIÓN ES QUE EL TRIGGER ES QUIEN DEBERÍA RESOLVER EL 
-- PROBLEMA.


-- REALIZAR UN INSERT A ESTA TABLA LUEGO DE CREADO EL TRIGGER.
