-- TAREA 1
-- SE SOLICITA QUE GENERE UN TRIGGER QUE SE ENCARGUE DE OTORGAR LA CLAVE 
-- PRIMARIA PARA LA TABLA DETALLE DE NOTAS Y OTRO PARA LA TABLA USUARIOS
-- TRABAJADA EN CLASES ANTERIORES.
-- COMO TAMBIÉN GENERAR OTRO TRIGGER QUE SE ENCARGUE DE TRABAJAR LOS 
-- CAMPOS DE TIPO TEXTO EVALUÁNDOLOS EN MAYÚSCULA PARA LA TABLA USUARIOS.

--CLAVE PRIMARIA PARA LA TABLA DETALLE DE NOTAS
CREATE OR REPLACE TRIGGER CACB_AUTO_PK_DETALLE
BEFORE INSERT
ON CACB_DETALLE_NOTAS
FOR EACH ROW
BEGIN
    SELECT CACB_PK_DETALLE_NOTAS.NEXTVAL
    INTO :NEW.NRO_DETALLE
    FROM DUAL;
END;
/

-- TAREA 1: CLAVE PRIMARIA PARA LA TABLA USUARIOS (CACB_USUARIO)
-- Utiliza la secuencia 'CACB_PK_USUARIO' ya definida en clases anteriores.
CREATE OR REPLACE TRIGGER CACB_AUTO_PK_USUARIO
BEFORE INSERT
ON CACB_USUARIO
FOR EACH ROW
BEGIN
    -- Asigna el siguiente valor de la secuencia CACB_PK_USUARIO al campo COD_USUARIO
    SELECT CACB_PK_USUARIO.NEXTVAL
    INTO :NEW.COD_USUARIO
    FROM DUAL;
END;
/

-- TAREA 1: CAMPOS DE TEXTO EN MAYÚSCULA PARA LA TABLA USUARIOS (CACB_USUARIO)
CREATE OR REPLACE TRIGGER CACB_MAYUSCULAS_USUARIO
BEFORE INSERT OR UPDATE
ON CACB_USUARIO
FOR EACH ROW
BEGIN
    -- Aplica la función UPPER() para convertir a mayúsculas
    :NEW.NOMBRE_USUARIO   := UPPER(:NEW.NOMBRE_USUARIO);
    :NEW.APELLIDO1_USUARIO := UPPER(:NEW.APELLIDO1_USUARIO);
    :NEW.APELLIDO2_USUARIO := UPPER(:NEW.APELLIDO2_USUARIO);
END;
