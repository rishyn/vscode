-- CÓMO PODRÍA GENERAR UN PROCEDIMIENTO INTEGRAL, QUE SE ENCARGUE DE REALIZAR
-- LAS 3 OPERACIONES DE LOS REQUERIMIENTOS ANTERIORES, ESTE DEBE INCLUIR
-- CONTROL DE CONCURRENCIA, COMO TAMBIÉN CONTROL Y MANEJO DE TRANSACCIONES.

CREATE OR REPLACE PROCEDURE CACB_IUD_USUARIOS(
	OPCION_P VARCHAR2
	COD_USUARIO_P NUMBER,
	NOMBRE_USUARIO_P VARCHAR2 DEFAULT NULL,
	APELLIDO1_USUARIO_P VARCHAR2 DEFAULT NULL,
	APELLIDO2_USUARIO_P VARCHAR2 DEFAULT NULL
)
IS
BEGIN
	LOCK TABLE CACB_USUARIO IN ROW EXCLUSIVE MODE;

	IF(UPPER(OPCION_P)='I')THEN
	INSERT INTO CACB_USUARIO(COD_USUARIO, NOMBRE_USUARIO, APELLIDO1_USUARIO, APELLIDO2_USUARIO)
		VALUES(COD_USUARIO_P, NOMBRE_USUARIO_P, APELLIDO1_USUARIO_P, APELLIDO2_USUARIO_P);
	END IF;

	IF(UPPER(OPCION_P)='U')THEN
	UPDATE CACB_USUARIO SET
		NOMBRE_USUARIO = NOMBRE_USUARIO_P,
		APELLIDO1_USUARIO = APELLIDO1_USUARIO_P,
		APELLIDO2_USUARIO = APELLIDO2_USUARIO_P
		WHERE(COD_USUARIO = COD_USUARIO_P);
	END IF;

	IF(UPPER(OPCION_P)='I')THEN
	DELETE FROM CACB_USUARIO
		WHERE(COD_USUARIO = COD_USUARIO_P);
	END IF;
	COMMIT;
	EXCEPTION
		WHEN PROGRAM_ERROR THEN
			RAISE_APPLICATION_ERROR(-6501,'ERROR INTERNO DEL PROGRAMA');
		WHEN OTHERS THEN
			RAISE_APPLICATION_ERROR(-20010,'UPSI FALLÉ =(')
		ROLLBACK;
END;



-- EJECUCIÓN DEL PA PARA INSERTAR
BEGIN
	DELETE FROM CACB_USUARIO;
	CACB_IUD_USUARIO('i',1,'CARLOS','CASTRO','BUSTAMANTE');
	CACB_IUD_USUARIO('i',2,'JUAN','SOLER','GARCIA');
	CACB_IUD_USUARIO('I',3,'MACARENA', 'URBINA', 'FIGUEROA');
	CACB_IUD_USUARIO('I',4,'JOSE', 'REYES', 'CASTRO');
END;

