-- QUISIERA SABER CUANTO LLEVA TRABAJANDO CADA EMPLEADO, EN SEMANAS. 
-- DE ACUERDO A LO SIGUIENTE: COD_EMPLEADO, NOMBRE CONCATENADO CON EL 
-- APELLIDO, FECHA_CONTRATO, SEMANAS_TRABAJADAS. SIEMPRE Y CUANDO PERTENEZCAN
-- AL DEPARTAMENTO 50 O AL 80, ORDENADOS DEL QUE MENOS HA TRABAJADO, AL QUE
-- MÁS HA TRABAJADO.

SELECT SYSDATE
FROM DUAL;



SELECT EMPLOYEE_ID AS "COD_EMPLEADO", UPPER(CONCAT(FIRST_NAME,CONCAT(' ',LAST_NAME))) AS "NOMBRE", HIRE_DATE AS "FECHA_CONTRATO", TRUNC((SYSDATE-HIRE_DATE)/7,0) AS "SEMAMAS_TRABAJADAS"
FROM OEHR_EMPLOYEES
WHERE DEPARTMENT_ID IN (50,80)
ORDER BY 4;
