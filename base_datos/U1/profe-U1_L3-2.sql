-- QUISIERA QUE PROBARAN LAS FUNCIONES ROUND, TRUNC Y MOD, SIN EMBARGO, NO QUIERO
-- QUE CONSULTEN UNA TABLA, PARA ELLO EN LA CLÁUSULA FROM SE DEBE INCLUIR LA TABLA
-- VIRTUAL DUAL, PARA ROUND PROBAR 45.5674 MOSTRANDO 3, 2, 1 Y 0 DECIMALES, LO MISMO
-- PARA LA FUNCIÓN TRUNC, SIN EMBARGO PARA EL MOD, ESTO TIENE QUE TRABAJARSE CON
-- LA DIVISIÓN ENTRE 54 ENTRE 3.
SELECT ROUND(45,5674,3), ROUND(45,5674,2), ROUND(45,5674,1), ROUND(45,5674,0)
FROM DUAL;

SELECT TRUNC(45,5674,3), TRUNC(45,5674,2), TRUNC(45,5674,1), TRUNC(45,5674,0)
FROM DUAL;

SELECT MOD(54/3)
FROM DUAL;

