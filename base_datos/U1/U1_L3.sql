--QUISIERA SABER EL PROMEDIO DE LOS SUELDOS DE TODOS LOS TRABAJADORES
SELECT ROUND (AVG(SALARY),0) AS "SUELDO_PROMEDIO"
FROM OEHR_EMPLOYEES;

--QUISIERA SABER EL PROMEDIO DE LOS SUELDOS DE LOS TRABAJADORES DEL
--DEPARTAMENTO 90
SELECT ROUND(AVG(SALARY),0) AS "SUELDO_PROMEDIO"
FROM OEHR_E,PLOYEES
WHERE DEPARTMENT_ID = 90;

--QUISIERA SABER LA PRIMERA Y ULTIMA DECHA DE CONTRATACION DE TODOS
--LOS EMPLEADOS
SELECT MIN(HIRE_DATE) AS "PRIMERA FECHA ", MAX(HIRE_DATE) AS "ULTIMA_FECHA"
FROM OEHR_EMPLOYEES;

--QUISIERA SABER LA CANTIDAD DE DEPARTAMENTO Q POSEEN POR LO MENOS
--UN TRABAJADOR
SELECT COUNT (DISTINCT NVL(DEPARTMENT_ID,0))
FROM OEHR_EMPLOYEES;

--QUISIERA SABER LA CANTIDAD DE TRABAJADORES DQUE PERCIBEN RENTAS MAYORES
--A LOS 10MIL DOLARES

SELECT COUNT (EMPLOYEES_ID)
FROM OEHR_EMPLOYEES
WHERE SALARY > 10000;

--QUISIERA SABER LA DIFERENCIA ENTRE LOS SUELDOS MINIMOS Y MAXIMOS

SELECT MAX(SALARY)- MIN(SALARY) AS "DIFERENCIA_SUELDOS"
FROM OEHR_EMPLOYEES;

--QUISIERA UN REPORTE CON EL PROMEDIODELOS SUELDOSDE CADA DEPARTAMENTO,
--MOSTRANDO LOS DEPARTAMENTOS CON SU CODIGO ASOCIADO
--COD_DEPARTAMENTO,PROM_SUELDO

SELECT DEPARTMENT_ID AS "COD_DEPARTAMENTO" , ROUND(AVG(SALARY),0) "PROM_SUELDOS"
FROM OEHR_EMPLOYEES;

