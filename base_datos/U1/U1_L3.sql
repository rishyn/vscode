--RESOLVAMOS EL REQUERIMIENTO ANTERIOR
SELECT DEPARTMENT_ID AS "COD_DEPARTAMENTO " , ROUND (AVG(SALARY),0) AS "PROM_SUELDO"
FROM OEHR_EMPLOYEES
GROUP BY DEPARTMENT_ID;

--Y SI QUISIERAMOS ORDENAR LOS SUELDOS PROMEDIO POR DEPARTAMENTO
SELECT DEPARTMENT_ID AS "COD_DEPARTAMENTO" , ROUND(AVG(SALARY),0) AS "PROM_SUELDO"
FROM OEHR_EMPLOYEES
GROUP BY DEPARTMENT_ID
ORDER BY 1;

--CON LA FINALIDAD DE GENERAR PRESUPUESTOS ,QUISIERA MONTAR UN REPORTE QUE SE
--ENCARGUE DE SABER CUAL ES EL TOTAL ACUMULADO DE LOS SUELDOS POR DEPARTAMENTO
--Y DE ACUERDO A SU CARGO, ORDENADO POR DEPARTAMENTO: COD_DEPARTAMENTO, CARGO
--SUMATORIA_SUELDO , ADEMAS EL SUELDO BAJO ELSIGUIENTE FORMATO: $XXX,XXX.XX

SELECT DEPARTMENT_ID AS "COD_DEPARTAMENTO", JOB_ID AS "CARGO" ,TO_CHAR (SUM(SALARY), '$999,999.99') AS "SUMATORIA_SUELDO"
FROM OEHR_EMPLOYEES
GROUP BY DEPARTMENT_ID,JOB_ID
ORDER BY DEPARTMENT_ID

--QUISIERA UN RESPORTE DONDE SE BUSQUE EL SUELDO MAXIMO POR DEPARTAMENTO, SIEMPRE
-- Y CUANDO ,ESTE SUELDO MAXIMO SEA MAYOR QUE , 10000.

SELECT MAX (SALARY), DEPARTMENT_ID
FROM OEHR_EMPLOYEES
WHERE MAX(SALARY) > 10000
GROUP BY DEPARTMENT_ID;

--NO PODEMOS USAR CLAUSULAS "WHERE" CUANDO USAMOS CLAUSULAS "GROUP BY"

SELECT MAX (SALARY)
FROM OEHR_EMPLOYEES
GROUP BY DEPARTMENT_ID;
HAVING MAX(SALARY) > 10000

--quisiera un reporte donde se busque el sueldo macimo por departamento, siempre,
--Y CUANDO, ESTE SUELDO MAXIMO SEA MAYOR QUE 10000, Y LOS DEPARTAMENTO ESTEN
--EN EL RANGO DEL 50 AL 90, ORDENAR POR DEPARTAMENTO DECENDENTE

SELECT MAX(SALARY)
FROM OEHR_EMPLOYEES
WHERE DEPARTMENT_ID BETWEEN 50 AND 90
GROUP BY DEPARTMENT_ID
HAVING MAX(SALARY)> 10000
ORDER BY 2 DESC;