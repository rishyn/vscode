### R1 : Trigger Autoincremental para LOG\_VENTAS
CREATE OR REPLACE TRIGGER LMLA_PK_LOG_VENTAS
BEFORE INSERT
ON LMLA_LOG_VENTAS
FOR EACH ROW
BEGIN
	NVL(MAX(COD_CLIENTE)+1,1)
	SELECT NVL(MAX(COD_LOG)+1,1) INTO :NEW.COD_LOG
	FROM LMLA_LOG_VENTAS;
END;

