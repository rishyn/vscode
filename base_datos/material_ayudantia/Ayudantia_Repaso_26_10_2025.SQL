### R2 : Trigger Mayúsculas para PRODUCTOS

CREATE OR REPLACE LMLA_MAYUS_PRODUCTOS
BEFORE INSERT
ON LMLA_PRODUCTOS 
FOR EACH ROW
BEGIN
	:NEW.NOMBRE_PRODUCTO:=UPPER(:NEW.NOMBRE_PRODUCTO);
END;


