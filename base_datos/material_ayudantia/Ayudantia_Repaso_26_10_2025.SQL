### R4 : Función para Obtener Precio de Producto

CREATE OR REPLACE FUNCTION LMLA_OBTENER_PRECIO_PRODUCTO(
	COD_PRODUCTO_F NUMBER
)
RETURN NUMBER
IS
	PRECIO NUMBER:=0;
BEGIN
	SELECT PRECIO_VENTA INTO PRECIO
	FROM LMLA_PRODUCTOS
	WHERE (COD_PRODUCTO=COD_PRODUCTO_F);
	
	RETURN PRECIO;

	EXCEPTION 
		WHEN NO_DATA_FOUND THEN
		RETURN 0;
END;
