"Se estima que la tienda tendrá un promedio de 100 actualizaciones de datos 
(cambios de stock, updates de ventas) por día. La empresa desea guardar logs por al menos 2 años. 
Se debe considerar un 20% de margen de seguridad por crecimiento inesperado."

