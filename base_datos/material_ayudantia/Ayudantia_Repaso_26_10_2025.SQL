### R5 : Procedimiento RUD para PRODUCTOS

CREATE OR REPLACE PROCEDURE LMLA_GESTIONAR_PRODUCTOS(
	OPCION_P VARCHAR2,
	COD_PRODUCTO_P NUMBER,
	NOMBRE_PRODUCTO_P VARCHAR2 DEFAULT NULL,
	PRECIO_COMPRA_P NUMBER DEFAULT NULL,
	PRECIO_VENTA_P NUMBER DEFAULT NULL,
	STOCK_P NUMBER DEFAULT NULL
)
IS
BEGIN
	LOCK TABLE LMLA_PRODUCTOS IN ROW EXCLUSIVE MODE;

	IF(UPPER(OPCION_P)='I') THEN
	    INSERT INTO LMLA_PRODUCTOS(COD_PRODUCTO,NOMBRE_PRODUCTO,PRECIO_COMPRA,PRECIO_VENTA,CANTIDAD,STOCK)
	    VALUES(COD_PRODUCTO_P,NOMBRE_PRODUCTO_P,PRECIO_COMPRA_P,PRECIO_VENTA_P,STOCK_P,STOCK_P);
	
	ELSIF(UPPER(OPCION_P)='U') THEN 
	    UPDATE LMLA_PRODUCTOS 
	    SET PRECIO_VENTA=PRECIO_VENTA_P,
	    STOCK=STOCK_P
	    WHERE(COD_PRODUCTO=COD_PRODUCTO_P);

	ELSIF(UPPER(OPCION_P)='D') THEN
	    DELETE FROM LMLA_PRODUCTOS
	    WHERE(COD_PRODUCTO=COD_PRODUCTO_P);
	END IF;
	COMMIT;
	EXCEPTION
	WHEN OTHERS THEN
	    RAISE_APPLICATION_ERROR(-20011,'ERROR EN EL PROCEDIMIENTO');
	ROLLBACK;
END;


