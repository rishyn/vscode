### R3 : Trigger "Sapo" para PRODUCTOS

CREATE OR REPLACE TRIGGER LMLA_SAPO_PRODUCTOS
AFTER UPDATE
ON LMLA_PRODUCTOS
FOR EACH ROW
BEGIN
	IF :NEW.STOCK<>:OLD.STOCK THEN
		INSERT INTO LMLA_LOG_VENTAS(INTRODUCCION,DETALLE,FECHAYHORA)
		VALUES('UPDATE','SE ACTUALIZO EL STOCK DEL PRODUCTO '||:NEW.COD_PRODUCTO||' DE '||:OLD.STOCK||' A '||:NEW.STOCK,SYSDATE)
	END IF;
END;

