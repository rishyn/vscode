### R6 : Procedimiento para Cargar DETALLE\_VENTA


CREATE OR REPLACE PROCEDURE LMLA_AGREGAR_PRODUCTO_VENTA(
	COD_VENTA_P NUMBER,
	COD_PRODUCTO_P  NUMBER,
	CANTIDAD_P NUMBER
)
IS
	PRECIO_UNITARIO NUMBER;
	PRECIO_TOTAL NUMBER;
BEGIN
	LOCK TABLE LMLA_DETALLE_VENTA IN ROW EXCLUSIVE MODE;
	PRECIO_UNITARIO:= LMLA_OBTENER_PRECIO_PRODUCTO(COD_PRODUCTO_P);
	PRECIO_TOTAL:= PRECIO_UNITARIO*CANTIDAD_P;
	
	INSERT INTO LMLA_DETALLE_VENTA(COD_VENTA,COD_PRODUCTO,CANTIDAD,VALOR_TOTAL)
	VALUES(COD_VENTA_P,COD_PRODUCTO_P,CANTIDAD_P,PRECIO_TOTAL);
	
	COMMIT;
	EXCEPTION
        WHEN STORAGE_ERROR THEN
		    RAISE_APPLICATION_ERROR(-20012,'ERROR AL AGREGAR EL DETALLE');
	ROLLBACK;
END;

