END;


##Ejercicio 4: Agrupar los procedimientos de Update, Insert y Delete en 1 solo

CREATE OR REPLACE PROCEDURE LMLA_GESTIONAR_PRODUCTOS(
	OPCION_P VARCHAR2,
	ID_PRODUCTO_P NUMBER,
	NOMBRE_PRODUCTO_P VARCHAR2 DEFAULT NULL,
	TIPO_PRODUCTO_P VARCHAR2 DEFAULT NULL,
	PRECIO_PRODUCTO_P NUMBER DEFAULT NULL
)
IS
BEGIN
	LOCK TABLE LMLA_PRODUCTOS IN ROW EXCLUSIVE MODE;
	
	IF UPPER(OPCION_P)='I' THEN
		INSERT INTO LMLA_PRODUCTOS(ID_PRODUCTO,NOMBRE_PRODUCTO,TIPO_PRODUCTO,PRECIO_PRODUCTO)
		VALUES(ID_PRODUCTO_P,NOMBRE_PRODUCTO_P,TIPO_PRODUCTO_P,PRECIO_PRODUCTO_P);

	ELSIF UPPER(OPCION_P)='D' THEN
		DELETE FROM LMLA_PRODUCTOS
		WHERE ID_PRODUCTO=ID_PRODUCTO_P;

	ELSIF UPPER(OPCION_P)='U' THEN
		UPDATE LMLA_PRODUCTOS
		SET NOMBRE_PRODUCTO=NOMBRE_PRODUCTO_P
			TIPO_PRODUCTO=TIPO_PRODUCTO_P
			PRECIO_PRODUCTO=PRECIO_PRODUCTO_P
		WHERE ID_PRODUCTO=ID_PRODUCTO_P;
	END IF;
	commit;
	EXCEPTION
			WHEN DUP_VAL_ON_INDEX THEN
				RAISE_APPLICATION_ERROR(-20100, 'ERROR: El ID de producto ' || ID_PRODUCTO_P || ' ya existe.');
        	WHEN STORAGE_ERROR THEN
	 			RAISE_APPLICATION_ERROR(-6500, 'ERROR DE MEMORIA');
        	WHEN OTHERS THEN
           		 RAISE_APPLICATION_ERROR(-20010, 'ERROR DESCONOCIDO');
    ROLLBACK;	
END;


BEGIN
	LMLA_GESTIONAR_PRODUCTOS('I',1,'QUIX','LIMPIEZA',1200);
END;


